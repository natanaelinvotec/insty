(function () {
  const D = window.INSTY_I18N, chaveLS = 'insty-lang';
  const idiomaInicial = () => {
    try { const s = localStorage.getItem(chaveLS); if (s && D[s]) return s; } catch (e) {}
    const n = (navigator.language || 'pt').slice(0, 2); return D[n] ? n : 'pt';
  };
  window.INSTY_setLang = function (lang) {
    if (!D[lang]) return;
    const t = D[lang];
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => { const k = el.dataset.i18n; if (t[k] != null) el.textContent = t[k]; });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => { const k = el.dataset.i18nHtml; if (t[k] != null) el.innerHTML = t[k]; });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { const k = el.dataset.i18nPlaceholder; if (t[k] != null) el.placeholder = t[k]; });
    document.querySelectorAll('[data-i18n-content]').forEach((el) => { const k = el.dataset.i18nContent; if (t[k] != null) el.content = t[k]; });
    document.title = t['meta.title'];
    document.querySelectorAll('[data-lang]').forEach((a) => a.classList.toggle('atual', a.dataset.lang === lang));
    try { localStorage.setItem(chaveLS, lang); } catch (e) {}
    document.dispatchEvent(new CustomEvent('insty:lang', { detail: { lang } }));
  };
  window.INSTY_t = (k) => (D[document.documentElement.lang.slice(0, 2)] || D.pt)[k] || k;
  document.addEventListener('click', (e) => {
    const a = e.target.closest('[data-lang]'); if (!a) return;
    e.preventDefault(); window.INSTY_setLang(a.dataset.lang);
  });
  const ini = idiomaInicial();
  if (ini !== 'pt') window.INSTY_setLang(ini); else document.querySelectorAll('[data-lang="pt"]').forEach((a) => a.classList.add('atual'));
})();
